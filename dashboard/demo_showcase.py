def _style(figure: go.Figure, title: str) -> go.Figure:
    figure.update_layout(
        title=title, template="plotly_dark", height=390,
        paper_bgcolor="#111c2e", plot_bgcolor="#111c2e",
        font={"color": "#f8fafc"}, margin={"l": 20, "r": 15,
                                           "t": 55, "b": 25},
    )
    return figure


def _price_chart(history: pd.DataFrame, label: str,
                 chart_type: str = "Line") -> go.Figure:
    fig = go.Figure()
    if chart_type == "Candlestick":
        fig.add_trace(go.Candlestick(
            x=history.index, open=history["Open"], high=history["High"],
            low=history["Low"], close=history["Close"],
            name=f"{label} · synthetic", increasing_line_color="#FF78B7",
            decreasing_line_color="#9BA9D1",
        ))
        fig.update_layout(xaxis_rangeslider_visible=False)
    else:
        fig.add_trace(go.Scatter(
            x=history.index, y=history["Close"], mode="lines",
            name=f"{label} · synthetic",
            line={"color": "#FF78B7", "width": 2.5},
        ))
    return _style(fig, f"Synthetic illustration · {label}")


def _pct_change(history: pd.DataFrame, days: int) -> float:
    close = history["Close"]
    offset = min(days, len(close) - 1)
    return float((close.iloc[-1] / close.iloc[-offset - 1] - 1) * 100)


@st.cache_data(show_spinner=False)
def _ranking() -> pd.DataFrame:
    rows = []
    benchmark = synthetic_history("ATLAS")
    for symbol in _assets():
        history = synthetic_history(symbol)
        risk = calculate_risk_metrics(history, benchmark)
        assessment = assess_stock(history)
        rows.append({
            "Symbol": symbol,
            "Fictional company": DEMO_ASSETS[symbol]["name"],
            "Sector": DEMO_ASSETS[symbol]["sector"],
            "Technical score / 100": assessment.score,
            "20-session move (%)": round(_pct_change(history, 20), 2),
            "Synthetic volatility (%)": round(
                risk["annualized_volatility_pct"], 2
            ),
            "Synthetic drawdown (%)": round(
                risk["maximum_drawdown_pct"], 2
            ),
        })
    return pd.DataFrame(rows)


def render_demo_stock_explorer() -> None:
    st.title(":primary[:material/science:] Quantitative Simulation Lab")
    _demo_banner()
    a, b, c = st.columns([2, 1, 1])
    with a:
        symbol = st.selectbox("Fictional company", _assets(),
                              format_func=_asset_label, key="qi_demo_explorer")
    with b:
        period = st.selectbox("Illustrative lookback", list(LOOKBACK),
                              index=3, key="qi_demo_period")
    with c:
        chart_type = st.selectbox("Chart", ["Line", "Candlestick"],
                                  key="qi_demo_chart_type")

    entire = synthetic_history(symbol)
    history = entire.tail(LOOKBACK[period])
    benchmark = synthetic_history("ATLAS")
    risk = calculate_risk_metrics(entire, benchmark)
    score = assess_stock(entire)
    metric_cols = st.columns(4)
    metric_cols[0].metric("Synthetic price", f"${history['Close'].iloc[-1]:,.2f}")
    metric_cols[1].metric("Simulated 1Y move",
                          f"{_pct_change(entire, 252):+.1f}%")
    metric_cols[2].metric("Historical formula: volatility",
                          f"{risk['annualized_volatility_pct']:.1f}%")
    metric_cols[3].metric("Illustrative score", f"{score.score}/100")

    st.plotly_chart(_price_chart(history, symbol, chart_type),
                    use_container_width=True)

    analytics, methodology = st.tabs(["Research analytics", "Model methodology"])
    with analytics:
        st.markdown("### Relative performance against a fictional index")
        comparison = benchmark.loc[history.index, "Close"]
        figure = go.Figure()
        for label, series, color in (
            (symbol, history["Close"], "#FF78B7"),
            ("ATLAS (fictional index)", comparison, "#9BA9D1"),
        ):
            normalized = 100 * series / series.iloc[0]
            figure.add_trace(go.Scatter(
                x=series.index, y=normalized, name=label,
                line={"color": color, "width": 2},
            ))
        st.plotly_chart(_style(
            figure, "Normalized synthetic value (starting at 100)"
        ), use_container_width=True)
        x, y, z = st.columns(3)
        x.metric("Maximum simulated drawdown",
                 f"{risk['maximum_drawdown_pct']:.1f}%")
        y.metric("Illustrative beta", f"{risk['beta_vs_spy']:.2f}")
        z.metric("Illustrative Sharpe", f"{risk['sharpe_ratio']:.2f}")
    with methodology:
        st.markdown(
            "The same risk and technical-scoring Python engines used by "
            "Quant Intelligence process these fictional OHLCV inputs. "
            "These formulas demonstrate risk calculations; the resulting scores have **not** been "
            "validated as predictions."
        )
        for explanation in score.reasons:
            st.write(f"• {explanation}")
        st.caption(
            "Synthetic scores are neither a probability of returns nor "
            "a recommendation to buy, sell, or hold."
        )


