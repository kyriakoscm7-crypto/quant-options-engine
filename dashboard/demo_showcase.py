@st.cache_data(show_spinner=False)
def synthetic_history(symbol: str) -> pd.DataFrame:
    """Create reproducible OHLCV data without any web or provider access."""
    if symbol not in DEMO_ASSETS:
        raise ValueError("Unknown fictional demonstration symbol")

    item = DEMO_ASSETS[symbol]
    dates = pd.bdate_range(end="2026-10-30", periods=1008)
    common = np.random.default_rng(92726).normal(0, 0.008, len(dates))
    generator = np.random.default_rng(item["seed"])
    daily = (
        item["drift"] / 252
        + item["beta"] * common
        + generator.normal(0, item["noise"], len(dates))
    )
    close = item["base"] * np.exp(np.cumsum(daily))
    opening = close * np.exp(generator.normal(0, 0.0025, len(dates)))
    high = np.maximum(opening, close) * (
        1 + generator.uniform(0.001, 0.009, len(dates))
    )
    low = np.minimum(opening, close) * (
        1 - generator.uniform(0.001, 0.009, len(dates))
    )
    volume = generator.integers(250_000, 4_500_000, len(dates))
    return pd.DataFrame(
        {"Open": opening, "High": high, "Low": low,
         "Close": close, "Volume": volume},
        index=dates,
    ).rename_axis("Illustrative date")


def _assets() -> list[str]:
    return [name for name in DEMO_ASSETS if name != "ATLAS"]


def _asset_label(symbol: str) -> str:
    return f"{DEMO_ASSETS[symbol]['name']} ({symbol} · fictional)"


