def render_demo_portfolio() -> None:
    st.title(":primary[:material/account_balance_wallet:] Portfolio Manager")
    _demo_banner()
    st.write(
        "Build a **fictional example portfolio** and explore its "
        "allocation and changing value using generated price series. "
        "Do not enter real account information."
    )
    symbols = ["ORION", "HARBOR", "CEDAR", "QUARTZ"]
    defaults = [20, 15, 30, 5]
    quantities = {}
    cols = st.columns(4)
    for i, symbol in enumerate(symbols):
        with cols[i]:
            quantities[symbol] = st.number_input(
                f"{symbol} example units", min_value=0, max_value=500,
                value=defaults[i], step=5, key=f"qi_demo_units_{symbol}"
            )
    prices = pd.DataFrame({
        sym: synthetic_history(sym)["Close"].tail(253).to_numpy()
        for sym in symbols
    }, index=synthetic_history("ATLAS").tail(253).index)
    basket = sum(
        (prices[sym] * qty for sym, qty in quantities.items()),
        start=pd.Series(0.0, index=prices.index),
    )
    if float(basket.iloc[-1]) <= 0:
        st.info("Add at least one fictional unit to view the portfolio.")
        return
    contribution = {
        sym: float(prices[sym].iloc[-1] * qty)
        for sym, qty in quantities.items() if qty > 0
    }
    changes = basket.pct_change().replace([np.inf, -np.inf], np.nan).dropna()
    vol = float(changes.std() * math.sqrt(252) * 100)
    maximum_drawdown = float(((basket / basket.cummax()) - 1).min() * 100)
    x, y, z = st.columns(3)
    x.metric("Illustrative portfolio value", f"${basket.iloc[-1]:,.2f}")
    y.metric("Synthetic annualized volatility", f"{vol:.1f}%")
    z.metric("Synthetic max drawdown", f"{maximum_drawdown:.1f}%")
    left, right = st.columns([1.5, 1])
    with left:
        normalized = basket / basket.iloc[0] * 100
        chart = go.Figure(go.Scatter(
            x=prices.index, y=normalized, mode="lines",
            line={"color": "#FF78B7", "width": 2.5},
            name="Synthetic portfolio",
        ))
        st.plotly_chart(_style(
            chart, "Example portfolio value · normalized to 100"
        ), use_container_width=True)
    with right:
        figure = go.Figure(go.Pie(
            labels=list(contribution), values=list(contribution.values()),
            hole=0.62,
        ))
        st.plotly_chart(_style(figure, "Illustrative allocation"),
                        use_container_width=True)
    st.caption(
        "Not an actual investment account. Static fictional units, "
        "fictional prices, and no trading costs or taxes."
    )


def forecast_demo_metrics(symbol: str, horizon: int) -> pd.DataFrame:
    """Build a chronological illustration with a simple no-change baseline."""
    if horizon not in (1, 5, 20):
        raise ValueError("Unsupported illustrative horizon")
    prices = synthetic_history(symbol)["Close"]
    # Prediction at day t uses only information available on or before t.
    past_trend = prices / prices.shift(10) - 1
    target = prices.shift(-horizon)
    data = pd.DataFrame({
        "Synthetic actual": target,
        "No-change baseline": prices,
        "Momentum example": prices * (
            1 + 0.4 * past_trend * (horizon / 10)
        ),
    }).dropna()
    # Retain the last 120 observations as a chronological held-out
    # illustration; no hyperparameters are fit to this example.
    return data.tail(120)


def render_demo_forecast() -> None:
    st.title(":primary[:material/psychology:] Forecast Intelligence")
    _demo_banner()
    st.write(
        "Compare a no-change baseline against a very simple momentum "
        "rule. This is a software demonstration on fictional prices, "
        "**not evidence that an AI model predicts markets**."
    )
    a, b = st.columns(2)
    with a:
        symbol = st.selectbox(
            "Fictional instrument", _assets(), format_func=_asset_label,
            key="qi_demo_forecast_symbol"
        )
    with b:
        horizon = st.selectbox(
            "Synthetic horizon", [1, 5, 20],
            format_func=lambda n: f"{n} illustrative sessions",
            key="qi_demo_forecast_horizon"
        )
    data = forecast_demo_metrics(symbol, horizon)
    actual = data["Synthetic actual"]
    baseline_mae = float((actual - data["No-change baseline"]).abs().mean())
    model_mae = float((actual - data["Momentum example"]).abs().mean())
    x, y = st.columns(2)
    x.metric("No-change baseline · synthetic MAE",
             f"${baseline_mae:.2f}")
    y.metric("Momentum rule · synthetic MAE", f"${model_mae:.2f}")
    chart = go.Figure()
    for name, color in (
        ("Synthetic actual", "#FFFFFF"),
        ("No-change baseline", "#9BA9D1"),
        ("Momentum example", "#FF78B7"),
    ):
        chart.add_trace(go.Scatter(
            x=data.index, y=data[name], name=name,
            line={"color": color, "width": 2},
        ))
    st.plotly_chart(
        _style(chart, "Illustrative holdout comparison · fictional data"),
        use_container_width=True,
    )
    st.info(
        "MAE is average absolute prediction error on the 120 synthetic "
        "evaluation points displayed here. This comparison does not "
        "validate future accuracy or make any trade recommendation."
    )


