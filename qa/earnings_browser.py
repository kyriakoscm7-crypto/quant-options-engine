"""Large synthetic week: bounded widgets, search, filtering, navigation, mobile."""
from pathlib import Path

from playwright.sync_api import expect, sync_playwright

output = Path('/tmp/qi-browser/earnings')
output.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch()
    for width in (390, 768, 1440):
        page = browser.new_page(viewport={'width': width, 'height': 1000})
        page.goto('http://127.0.0.1:18525')
        page.get_by_text('Showing 10', exact=False).wait_for()
        expect(page.locator('.earnings-card')).to_have_count(10)
        expect(page.get_by_text('Shared weekly snapshot', exact=False)).to_be_visible()
        expect(page.get_by_role('button', name='Research ')).to_have_count(10)
        expect(page.locator('.earnings-card').first).to_contain_text('#1 · AAPL')
        expect(page.locator('.earnings-card').first).to_contain_text('Fri, Nov 13, 2026 · BMO')
        expect(page.locator('.earnings-card').nth(1)).to_contain_text('Mon, Nov 09, 2026 · AMC')
        expect(page.get_by_text('Editorial priority · Curated recognition and earnings attention, not market-cap ranking', exact=True)).to_be_visible()
        assert page.get_by_role('button', name='Refresh', exact=True).count() == 0
        page.screenshot(path=str(output / f'calendar-{width}.png'), full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        page.get_by_role('button', name='Show 10 more', exact=True).click()
        page.get_by_text('Showing 12', exact=False).wait_for()
        expect(page.locator('.earnings-card')).to_have_count(12)
        search = page.get_by_role('textbox', name='Search earnings companies')
        search.fill('absent')
        search.press('Enter')
        page.get_by_text('0 matching earnings events', exact=False).wait_for()
        search.fill('Synthetic Nvidia')
        search.press('Enter')
        page.get_by_role('button', name='Research NVDA', exact=True).wait_for()
        expect(page.locator('.earnings-card')).to_have_count(1)
        search.fill('')
        search.press('Enter')
        page.get_by_text('Showing 10', exact=False).wait_for()
        page.get_by_text('Mon', exact=True).click()
        page.get_by_text('254 matching earnings events', exact=False).wait_for()
        expect(page.locator('.earnings-card')).to_have_count(10)
        page.get_by_role('button', name='Research T0000', exact=True).click()
        page.get_by_text('Research selection: T0000', exact=True).wait_for()
        page.goto('http://127.0.0.1:18525/?no_featured=1')
        expect(page.get_by_text("No featured major companies in this week's provider events · Date, then ticker", exact=True)).to_be_visible()
        expect(page.locator('.earnings-card')).to_have_count(0)
        page.get_by_text('All week', exact=True).click()
        expect(page.locator('.earnings-card')).to_have_count(10)
        expect(page.locator('.earnings-card').first).to_contain_text('T0000')
        search = page.get_by_role('textbox', name='Search earnings companies')
        search.fill('T1269')
        search.press('Enter')
        expect(page.get_by_role('button', name='Research T1269', exact=True)).to_be_visible()
        page.goto('http://127.0.0.1:18525/?issuer_review=1')
        search = page.get_by_role('textbox', name='Search earnings companies')
        search.fill('CSCO')
        search.press('Enter')
        expect(page.locator('.earnings-card')).to_have_count(1)
        expect(page.locator('.earnings-card')).to_contain_text('Thu, Nov 12, 2026 · AMC')
        expect(page.get_by_role('link', name='Official announcement', exact=True)).to_have_attribute('href', 'https://example.com/synthetic-issuer')
        page.get_by_text('Wed', exact=True).click()
        expect(page.locator('.earnings-card')).to_have_count(0)
        page.get_by_text('Thu', exact=True).click()
        expect(page.locator('.earnings-card')).to_have_count(1)
        page.close()
    browser.close()
print('Earnings desktop/mobile browser regression passed')
